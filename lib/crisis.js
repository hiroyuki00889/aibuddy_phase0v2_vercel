// 自殺・自傷のサインを含む発言を検知する（相談窓口カードの表示と、AIへの指示の切り替えに使う）
// 誤検知（「恥ずかしくて死にたい」など）は許容する。カードは会話を止めず、そっと添えるだけのため。
const CRISIS_PATTERNS = [
  /死にたい|しにたい|死んでしまいたい|死のうかな|死のうと思|死ねたら/,
  /消えたい|きえたい|消えてしまいたい|いなくなりたい/,
  /自殺|じさつ|自死/,
  /生きて(い)?たくない|生きるのが(つらい|辛い|しんどい)|生きて(い)?る意味(が|は)?(ない|無い|わからない)|生きる意味(が|は)?(ない|無い|わからない)/,
  /リスカ|リストカット|自傷|自分を傷つけ/,
  /首(を)?吊|首つり|飛び降り(たい|よう|ようかな)|オーバードーズ|薬を(大量|いっぱい|全部)/,
  /遺書/
];

export function detectCrisis(text) {
  if (typeof text !== "string") return false;
  const normalized = text.replace(/\s+/g, "");
  return CRISIS_PATTERNS.some((pattern) => pattern.test(normalized));
}

export function getLatestUserText(messages) {
  if (!Array.isArray(messages)) return "";
  for (let i = messages.length - 1; i >= 0; i--) {
    if (messages[i]?.role === "user") return String(messages[i].content ?? "");
  }
  return "";
}

